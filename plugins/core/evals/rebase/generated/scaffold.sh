# Both sides add a route file and regenerate the generated index, so the
# index conflicts. The checksum line cannot be produced by hand-merging the
# two sides; only rerunning ./gen.sh gives the right file.
source "$(dirname "$0")/../_lib/repo.sh"

init_repo
mkdir -p routes generated
cat > gen.sh <<'EOF'
#!/bin/sh
# Rebuilds generated/routes.txt from routes/*.txt.
set -eu
cd "$(dirname "$0")"
body=$(cat routes/*.txt | LC_ALL=C sort)
sum=$(printf '%s\n' "$body" | sha256sum | cut -c1-16)
{
  echo "# GENERATED by ./gen.sh from routes/*.txt. Do not edit; rerun ./gen.sh."
  echo "# checksum: $sum"
  printf '%s\n' "$body"
} > generated/routes.txt
EOF
chmod +x gen.sh
printf 'GET /users\nPOST /users\n' > routes/users.txt
./gen.sh
commit "Initial routes"
publish_main

git checkout -qb feature
printf 'GET /search\n' > routes/search.txt
./gen.sh
commit "Add search route"

on_upstream() {
  printf 'GET /billing/invoices\n' > routes/billing.txt
  ./gen.sh
  commit "Add billing route"
}
upstream on_upstream
